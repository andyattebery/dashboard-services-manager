using Dsm.Shared.Models;

namespace Dsm.Managers.Services;

// Merges every provider source's copy of the same service into one entry, so a label on one copy
// applies even when another source publishes the service: a container's dsm.ignore hides it, and
// its dsm.category or dsm.icon shows, even when the container has no URL and Traefik supplies the
// route. Copies are the same service when they share (Name, Hostname) once defaults are applied,
// or (Url, Hostname).
//
// Per field, the first copy that has a value wins, in provider-type order:
// - Url: Traefik, Docker, Swarm, YAML file. Traefik's route is what is actually served.
// - Name, Category, Icon, ImageUrl, ServiceDefaultsName: Docker, Swarm, Traefik, YAML file. A
//   Traefik copy only knows a router name, so container labels always apply.
// A service is dropped when any copy is ignored or has a name in IgnoredServiceNames, or when no
// copy has a URL. The copy that supplied the URL owns the merged entry.
public class ServiceMerger
{
    // A ProviderId is {hostname}-{type}[-{index}], built by ProviderService.AssignProviderIds in
    // Dsm.Provider.App, with the type lower-cased. A ProviderId that doesn't end in one of these
    // (a custom override) ranks after all of them.
    private static readonly string[] UrlOrder = ["traefik", "docker", "swarm", "yamlfile"];
    private static readonly string[] ValueOrder = ["docker", "swarm", "traefik", "yamlfile"];

    private readonly ServiceWithDefaultsFactory _serviceWithDefaultsFactory;

    public ServiceMerger(ServiceWithDefaultsFactory serviceWithDefaultsFactory)
    {
        _serviceWithDefaultsFactory = serviceWithDefaultsFactory;
    }

    public List<Service> Merge(IEnumerable<Service> copies, IReadOnlyCollection<string> ignoredServiceNames)
    {
        var copyList = copies.ToList();
        var groups = new UnionFind(copyList.Count);
        var firstByName = new Dictionary<(string, string?), int>();
        var firstByUrl = new Dictionary<(string, string?), int>();
        for (var i = 0; i < copyList.Count; i++)
        {
            // Grouping uses the names defaults produce: the Traefik provider's "traefik" and a
            // container named Traefik both become "Traefik (nas-01)".
            var name = _serviceWithDefaultsFactory.CreateWithDefaults(copyList[i]).Name;
            Link(groups, firstByName, (name, copyList[i].Hostname), i);
            if (!string.IsNullOrWhiteSpace(copyList[i].Url))
            {
                Link(groups, firstByUrl, (copyList[i].Url!, copyList[i].Hostname), i);
            }
        }

        return Enumerable.Range(0, copyList.Count)
            .GroupBy(groups.Find)
            .Select(group => MergeGroup(group.Select(i => copyList[i]).ToList(), ignoredServiceNames))
            .OfType<Service>()
            .OrderBy(s => s.Name, StringComparer.Ordinal)
            .ThenBy(s => s.Hostname, StringComparer.Ordinal)
            .ThenBy(s => s.Url, StringComparer.Ordinal)
            .ToList();
    }

    private Service? MergeGroup(List<Service> copies, IReadOnlyCollection<string> ignoredServiceNames)
    {
        if (copies.Any(c => c.Ignore || ignoredServiceNames.Contains(c.Name, StringComparer.OrdinalIgnoreCase)))
        {
            return null;
        }

        var urlSource = InOrder(copies, UrlOrder).FirstOrDefault(c => !string.IsNullOrWhiteSpace(c.Url));
        if (urlSource is null)
        {
            return null;
        }

        var byValue = InOrder(copies, ValueOrder);
        string? First(Func<Service, string?> field) =>
            byValue.Select(field).FirstOrDefault(v => !string.IsNullOrEmpty(v));

        // Hostname is part of both grouping keys, so every copy in the group shares it.
        var merged = new Service(
            First(c => c.Name) ?? byValue[0].Name,
            urlSource.Url,
            First(c => c.Category),
            First(c => c.Icon),
            First(c => c.ImageUrl),
            byValue[0].Hostname,
            ignore: false,
            autogenerated: true,
            serviceDefaultsName: First(c => c.ServiceDefaultsName),
            providerId: urlSource.ProviderId);
        return _serviceWithDefaultsFactory.CreateWithDefaults(merged);
    }

    private static List<Service> InOrder(List<Service> copies, string[] typeOrder) =>
        copies
            .OrderBy(c => Rank(c.ProviderId, typeOrder))
            .ThenBy(c => c.ProviderId, StringComparer.Ordinal)
            .ThenBy(c => c.Name, StringComparer.Ordinal)
            .ThenBy(c => c.Url, StringComparer.Ordinal)
            .ToList();

    private static int Rank(string? providerId, string[] typeOrder)
    {
        var index = Array.IndexOf(typeOrder, ProviderType(providerId));
        return index >= 0 ? index : typeOrder.Length;
    }

    private static string? ProviderType(string? providerId)
    {
        if (string.IsNullOrEmpty(providerId))
        {
            return null;
        }
        var segments = providerId.Split('-');
        var last = segments.Length - 1;
        if (last > 0 && segments[last].Length > 0 && segments[last].All(char.IsAsciiDigit))
        {
            last--;
        }
        return segments[last];
    }

    private static void Link(UnionFind groups, Dictionary<(string, string?), int> firstByKey, (string, string?) key, int index)
    {
        if (firstByKey.TryGetValue(key, out var first))
        {
            groups.Union(index, first);
        }
        else
        {
            firstByKey[key] = index;
        }
    }

    private sealed class UnionFind
    {
        private readonly int[] _parent;

        public UnionFind(int count) => _parent = Enumerable.Range(0, count).ToArray();

        public int Find(int i)
        {
            while (_parent[i] != i)
            {
                _parent[i] = _parent[_parent[i]];
                i = _parent[i];
            }
            return i;
        }

        public void Union(int a, int b) => _parent[Find(a)] = Find(b);
    }
}
