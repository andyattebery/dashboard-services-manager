using Dsm.Managers.Configuration;
using Dsm.Shared.Models;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace Dsm.Managers;

// Remembers when each ProviderId last posted, so entries from a provider source that has gone
// silent can be removed. The combiner alone can't do this: a ProviderId missing from one POST looks
// exactly like a source that failed that cycle, so once a source is dropped from a provider's
// config, or its host is gone, its entries would stay forever.
//
// Only DashboardCommandProcessor calls this, under DashboardWriteCoordinator, so it takes no lock.
// State is in memory: after a manager restart, every ProviderId already in a dashboard file starts
// a fresh timeout, so a restart can delay a removal but never cause an early one.
public sealed class StaleProviderTracker
{
    private readonly TimeSpan _timeout;
    private readonly TimeProvider _timeProvider;
    private readonly ILogger<StaleProviderTracker> _logger;
    private readonly Dictionary<string, long> _lastSeen = new();
    private long? _lastPost;
    private long _now;

    public StaleProviderTracker(
        IOptions<ManagerOptions> managerOptions,
        TimeProvider timeProvider,
        ILogger<StaleProviderTracker> logger)
    {
        _timeout = managerOptions.Value.StaleProviderTimeout;
        _timeProvider = timeProvider;
        _logger = logger;
    }

    // Call once per POST, before FindStale, with the ProviderIds of the services the POST kept.
    public void MarkSeen(IEnumerable<string> providerIds)
    {
        _now = _timeProvider.GetTimestamp();
        if (_lastPost is { } lastPost && _timeProvider.GetElapsedTime(lastPost, _now) > _timeout)
        {
            // Nobody posted for longer than the timeout, so the outage was on the manager's side
            // (network, partition) and no provider's silence says it's gone. Start every timeout
            // over, as after a restart, instead of dropping every other provider's entries until
            // each one posts again.
            _logger.LogInformation(
                "No provider posted for {Gap}, longer than StaleProviderTimeout {Timeout}; restarting the timeout for {Count} ProviderIds",
                _timeProvider.GetElapsedTime(lastPost, _now), _timeout, _lastSeen.Count);
            _lastSeen.Clear();
        }
        _lastPost = _now;

        foreach (var providerId in providerIds)
        {
            _lastSeen[providerId] = _now;
        }
    }

    // Returns the ProviderIds of the autogenerated services that haven't posted for longer than the
    // timeout, with how long each has gone unseen. Measured against the last MarkSeen, so every
    // dashboard in one POST gets the same answer. A ProviderId seen here for the first time starts
    // its timeout now. None is ever forgotten: the next dashboard's call would restart it.
    public IReadOnlyDictionary<string, TimeSpan> FindStale(IEnumerable<Service> services)
    {
        var stale = new Dictionary<string, TimeSpan>();
        var providerIds = services
            .Where(s => s.Autogenerated)
            .Select(s => s.ProviderId)
            .OfType<string>()
            .Distinct();
        foreach (var providerId in providerIds)
        {
            if (!_lastSeen.TryGetValue(providerId, out var lastSeen))
            {
                _lastSeen[providerId] = _now;
                continue;
            }

            var unseenFor = _timeProvider.GetElapsedTime(lastSeen, _now);
            if (unseenFor > _timeout)
            {
                stale[providerId] = unseenFor;
            }
        }
        return stale;
    }
}
