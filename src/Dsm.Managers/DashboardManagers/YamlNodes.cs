using Dsm.Shared.Models;
using YamlDotNet.Core;
using YamlDotNet.RepresentationModel;

namespace Dsm.Managers.DashboardManagers;

// Content DSM doesn't own (hand-written entries, Dashy section fields and top-level keys, the rest
// of Homepage's settings.yaml) is written back from its YAML nodes, which keep every field and each scalar's text and quoting style. Nodes
// can sit inside the object graph the serializer writes, because they implement IYamlConvertible.
internal static class YamlNodes
{
    // Loads the whole document, so an alias resolves even when its anchor is in another entry.
    // Anchors are then cleared: each node emits its full content, and can't collide with the
    // anchors (o0, o1, …) the serializer assigns to objects DSM's own entries share.
    public static YamlNode? Load(string text)
    {
        var stream = new YamlStream();
        stream.Load(new StringReader(text));
        if (stream.Documents.Count == 0) return null;

        var root = stream.Documents[0].RootNode;
        foreach (var node in root.AllNodes)
        {
            node.Anchor = AnchorName.Empty;
        }
        return root;
    }

    public static YamlNode? Child(YamlMappingNode map, string key)
    {
        foreach (var (k, v) in map.Children)
        {
            if (k is YamlScalarNode s && s.Value == key) return v;
        }
        return null;
    }

    // Replaces the value under key in place, or appends the key when the mapping doesn't have it.
    public static void Set(YamlMappingNode map, string key, YamlNode value)
    {
        var existingKey = map.Children.Keys.FirstOrDefault(k => k is YamlScalarNode s && s.Value == key);
        if (existingKey is null)
        {
            map.Add(key, value);
        }
        else
        {
            map.Children[existingKey] = value;
        }
    }

    // A mapping's children keyed by their scalar text, so callers can replace a value by name
    // and keep the key's position.
    public static Dictionary<object, object> ToDictionary(YamlMappingNode map)
    {
        var result = new Dictionary<object, object>();
        foreach (var (k, v) in map.Children)
        {
            result[((YamlScalarNode)k).Value ?? string.Empty] = v;
        }
        return result;
    }

    // Hand-written entries by the Service each one reads as. The combiner passes them through
    // unchanged, so WriteServices finds each one again. The first in the file wins, as in the
    // combiner's dedupe.
    public static Dictionary<Service, YamlMappingNode> IndexHandWritten(
        IEnumerable<(Service Service, YamlMappingNode Node)> entries)
    {
        var index = new Dictionary<Service, YamlMappingNode>();
        foreach (var (service, node) in entries)
        {
            if (!service.Autogenerated) index.TryAdd(service, node);
        }
        return index;
    }
}
