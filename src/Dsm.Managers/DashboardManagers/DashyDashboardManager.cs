using System.Globalization;
using Dsm.Managers.Configuration;
using Dsm.Managers.DashboardManagers.Dashy;
using Dsm.Managers.Services;
using Dsm.Managers.Services.IconSources;
using Dsm.Shared.Extensions;
using Dsm.Shared.Models;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using YamlDotNet.RepresentationModel;
using YamlDotNet.Serialization;
using YamlDotNet.Serialization.NamingConventions;

namespace Dsm.Managers.DashboardManagers;

public class DashyDashboardManager : IDashboardManager
{
    public const string ConfigFileName = "conf.yml";
    private const string SectionsKey = "sections";
    private const string NameKey = "name";
    private const string IconKey = "icon";
    private const string ItemsKey = "items";

    private readonly ServiceDefaultOptions _serviceDefaultOptions;
    private readonly DashboardManagerConfig _config;
    private readonly IconResolver _iconResolver;
    private readonly ILogger<DashyDashboardManager> _logger;

    public DashyDashboardManager(
        DashboardManagerConfig config,
        IOptions<ServiceDefaultOptions> defaultOptions,
        IconResolver iconResolver,
        ILogger<DashyDashboardManager> logger)
    {
        _serviceDefaultOptions = defaultOptions.Value;
        _config = config;
        _iconResolver = iconResolver;
        _logger = logger;
    }

    public IReadOnlyDictionary<DashboardIconSourceType, string> NativeIconSourcePrefixes { get; }
        = new Dictionary<DashboardIconSourceType, string>
        {
            [DashboardIconSourceType.HomarrLabs] = "hl-",
            [DashboardIconSourceType.SelfhSt] = "sh-",
            [DashboardIconSourceType.MaterialDesignIcons] = "mdi-",
        };

    public DashboardManagerType Type => DashboardManagerType.Dashy;
    public string ConfigFilePath => Path.Combine(_config.DashboardConfigDirectoryPath, ConfigFileName);

    public async Task<List<Service>> ListServices()
    {
        var (_, items) = await LoadConfig();
        return items.Select(i => i.Service).ToList();
    }

    public async Task<bool> WriteServices(List<Service> services)
    {
        var (root, items) = await LoadConfig();
        var handWritten = YamlNodes.IndexHandWritten(items);

        var resolvedIcons = new Dictionary<Service, (string? Icon, string? ImageUrl)>();
        foreach (var s in services.Where(s => !handWritten.ContainsKey(s)))
        {
            resolvedIcons[s] = await _iconResolver.Resolve(s, this);
        }

        var sectionIcons = await ResolveSectionIcons(services);
        var dashySections = CreateDashySections(
            services, handWritten, resolvedIcons, sectionIcons, IndexSectionsByName(root));

        // Every top-level key other than sections (appConfig, pageInfo, …) goes back as read.
        var dashyConfig = root is null ? new Dictionary<object, object>() : YamlNodes.ToDictionary(root);
        dashyConfig[SectionsKey] = dashySections;

        var sw = new StringWriter();
        CreateSerializer().Serialize(sw, dashyConfig);
        return await YamlFileWriter.WriteIfChanged(ConfigFilePath, sw.ToString());
    }

    private static Service ToService(DashySection dashySection, DashyItem dashyItem)
    {
        var (icon, imageUrl) = GetIconOrImageUrl(dashyItem.Icon);
        var tags = dashyItem.Tags ?? [];
        var hostname = GetHostnameFromTags(tags);
        var providerId = GetProviderIdFromTags(tags);
        var autogenerated = tags.Contains(DashyItem.AutogeneratedTag);
        return new Service(dashyItem.Title, dashyItem.Url, dashySection.Name, icon,
            imageUrl, hostname, false, autogenerated, providerId: providerId);
    }

    private static (string? icon, string? imageUrl) GetIconOrImageUrl(string? icon)
    {
        if (string.IsNullOrEmpty(icon)) return (null, null);
        return icon.StartsWith("http", StringComparison.OrdinalIgnoreCase) ? (null, icon) : (icon, null);
    }

    private static string? GetHostnameFromTags(List<string> tags)
    {
        return GetTagValue(tags, "host=");
    }

    private static string? GetProviderIdFromTags(List<string> tags)
    {
        return GetTagValue(tags, "provider=");
    }

    private static string? GetTagValue(List<string> tags, string prefix)
    {
        foreach (var tag in tags)
        {
            if (tag.StartsWith(prefix, StringComparison.Ordinal) && tag.Length > prefix.Length)
            {
                return tag.Substring(prefix.Length);
            }
        }

        return null;
    }

    private List<Dictionary<object, object>> CreateDashySections(
        List<Service> services,
        IReadOnlyDictionary<Service, YamlMappingNode> handWritten,
        IReadOnlyDictionary<Service, (string? Icon, string? ImageUrl)> resolvedIcons,
        IReadOnlyDictionary<string, string?> sectionIcons,
        IReadOnlyDictionary<string, YamlMappingNode> existingSections)
    {
        var sectionNameToServicesMapping = new Dictionary<string, List<Service>>();
        foreach (var service in services)
        {
            sectionNameToServicesMapping.AddToLookup((service.Category ?? string.Empty).ToLowerInvariant(), service);
        }

        // Hand-written items go back as read; only DSM's own are rebuilt.
        var dashySections = sectionNameToServicesMapping
            .Select(kvp => (Name: ResolveCategoryDisplayName(kvp.Key), Services: kvp.Value))
            .OrderBy(s => s.Name)
            .Select(s => CreateDashySection(s.Name, s.Services
                .OrderBy(service => service.Name)
                .Select(service => handWritten.TryGetValue(service, out var node)
                    ? node
                    : (object)DashyItem.Create(service, resolvedIcons[service].Icon,
                        resolvedIcons[service].ImageUrl, _config.EnableStatusMonitoring))
                .ToList(), sectionIcons, existingSections))
            .ToList();
        return dashySections;
    }

    // A section starts from the existing one with the same name, so the fields DSM doesn't model
    // (displayData, …) survive. Its icon is replaced only when the category has one configured.
    private static Dictionary<object, object> CreateDashySection(
        string displayName,
        List<object> dashyItems,
        IReadOnlyDictionary<string, string?> sectionIcons,
        IReadOnlyDictionary<string, YamlMappingNode> existingSections)
    {
        var dashySection = existingSections.TryGetValue(displayName, out var existing)
            ? YamlNodes.ToDictionary(existing)
            : new Dictionary<object, object>();
        dashySection[NameKey] = displayName;
        if (sectionIcons.TryGetValue(displayName, out var sectionIcon) && sectionIcon is not null)
        {
            dashySection[IconKey] = sectionIcon;
        }
        dashySection[ItemsKey] = dashyItems;
        return dashySection;
    }

    // Existing sections by name. A name that appears twice keeps its first section, matching how
    // CreateDashySections folds categories that differ only by case into one section.
    private static Dictionary<string, YamlMappingNode> IndexSectionsByName(YamlMappingNode? root)
    {
        var sections = new Dictionary<string, YamlMappingNode>(StringComparer.OrdinalIgnoreCase);
        if (root is null || YamlNodes.Child(root, SectionsKey) is not YamlSequenceNode sectionNodes)
        {
            return sections;
        }
        foreach (var sectionNode in sectionNodes.Children.OfType<YamlMappingNode>())
        {
            if (YamlNodes.Child(sectionNode, NameKey) is YamlScalarNode { Value: { Length: > 0 } name })
            {
                sections.TryAdd(name, sectionNode);
            }
        }
        return sections;
    }

    private string ResolveCategoryDisplayName(string category)
    {
        if (string.IsNullOrEmpty(category))
            return "Uncategorized";
        if (_serviceDefaultOptions.Categories.TryGetValue(category, out var c)
            && !string.IsNullOrEmpty(c.Name))
            return c.Name;
        return CultureInfo.InvariantCulture.TextInfo.ToTitleCase(category.ToLowerInvariant());
    }

    private async Task<Dictionary<string, string?>> ResolveSectionIcons(List<Service> services)
    {
        // Compute distinct section names (title-cased) the same way CreateDashySections does,
        // then resolve each category's configured icon through IconResolver — prefix
        // translation, native pass-through, CDN probe, all the same as service icons. No
        // fallback chain: a category with no defaults icon stays unset, and the section keeps
        // whatever icon it already has.
        var distinctSectionNames = services
            .Select(s => ResolveCategoryDisplayName(s.Category ?? string.Empty))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();

        var resolved = new Dictionary<string, string?>(StringComparer.OrdinalIgnoreCase);
        foreach (var sectionName in distinctSectionNames)
        {
            var rawIcon = _serviceDefaultOptions.FindCategory(sectionName)?.Icon;
            var (icon, imageUrl) = await _iconResolver.ResolveIcon(rawIcon, this);
            resolved[sectionName] = imageUrl ?? icon;
        }
        return resolved;
    }

    // The file's root mapping, and every item as the Service it reads as paired with its YAML
    // node. The typed parse and the node tree come from the same text, so they line up section by
    // section and item by item.
    private async Task<(YamlMappingNode? Root, List<(Service Service, YamlMappingNode Node)> Items)> LoadConfig()
    {
        if (!File.Exists(ConfigFilePath))
        {
            _logger.LogWarning("Dashy config file '{Path}' does not exist; using empty config.",
                ConfigFilePath);
            return (null, []);
        }

        var text = await File.ReadAllTextAsync(ConfigFilePath);
        var dashyConfig = CreateDeserializer().Deserialize<DashyConfig>(text) ?? new DashyConfig();
        var root = YamlNodes.Load(text) as YamlMappingNode;
        var sectionNodes = root is null
            ? []
            : (YamlNodes.Child(root, SectionsKey) as YamlSequenceNode)?.Children ?? [];

        var items = new List<(Service, YamlMappingNode)>();
        for (var i = 0; i < dashyConfig.Sections.Count; i++)
        {
            var dashySection = dashyConfig.Sections[i];
            var itemNodes = (YamlNodes.Child((YamlMappingNode)sectionNodes[i], ItemsKey) as YamlSequenceNode)?.Children ?? [];
            for (var j = 0; j < dashySection.Items.Count; j++)
            {
                items.Add((ToService(dashySection, dashySection.Items[j]), (YamlMappingNode)itemNodes[j]));
            }
        }
        return (root, items);
    }

    private static IDeserializer CreateDeserializer()
    {
        return new DeserializerBuilder()
            .WithNamingConvention(CamelCaseNamingConvention.Instance)
            .IgnoreUnmatchedProperties()
            .Build();
    }

    private static ISerializer CreateSerializer()
    {
        return new SerializerBuilder()
            .WithNamingConvention(CamelCaseNamingConvention.Instance)
            .ConfigureDefaultValuesHandling(DefaultValuesHandling.OmitNull)
            .Build();
    }
}