    [Test]
    public async Task FansOutToBothManagersAndPreservesEachDashboardsHandEntries()
    {
        using var dashyDir = TestTempDir.Create("dsm_cp_fanout_dashy");
        using var homepageDir = TestTempDir.Create("dsm_cp_fanout_hp");
        var dashyPath = dashyDir.RootedPath(DashyDashboardManager.ConfigFileName);
        var homepagePath = homepageDir.RootedPath(HomepageDashboardManager.ServicesFileName);

        File.WriteAllText(dashyPath, """
            ---
            sections:
            - name: Existing
              items:
              - title: HandWrittenDashyEntry
                url: https://hand.example
                icon: favicon-local
                tags:
                - host=elsewhere
            """);

        File.WriteAllText(homepagePath, """
            - Existing:
                - HandWrittenHomepageEntry:
                    href: https://hand-hp.example
                    server: elsewhere
            """);

        var processor = BuildProcessor(
            (DashboardManagerType.Dashy, dashyDir.Path),
            (DashboardManagerType.Homepage, homepageDir.Path));

        var incoming = new List<Service>
        {
            new Service("Jellyfin", "https://jellyfin.new", "Media", null, null, "host-1", false),
        };

        var response = await processor.UpdateWithServicesFromProvider(incoming);

        Assert.Multiple(() =>
        {
            Assert.That(response.Keys, Is.EquivalentTo(new[] { "Dashy", "Homepage" }));
            Assert.That(response["Dashy"].Any(s => s.Name == "Jellyfin"), Is.True);
            Assert.That(response["Dashy"].Any(s => s.Name == "HandWrittenDashyEntry"), Is.True,
                "Dashy's hand-written entry survives in Dashy");
            Assert.That(response["Dashy"].Any(s => s.Name == "HandWrittenHomepageEntry"), Is.False,
                "Homepage's hand-written entry does not leak into Dashy");
            Assert.That(response["Homepage"].Any(s => s.Name == "Jellyfin"), Is.True);
            Assert.That(response["Homepage"].Any(s => s.Name == "HandWrittenHomepageEntry"), Is.True,
                "Homepage's hand-written entry survives in Homepage");
            Assert.That(response["Homepage"].Any(s => s.Name == "HandWrittenDashyEntry"), Is.False,
                "Dashy's hand-written entry does not leak into Homepage");
        });

        var dashyYaml = await File.ReadAllTextAsync(dashyPath);
        var homepageYaml = await File.ReadAllTextAsync(homepagePath);
        Assert.Multiple(() =>
        {
            Assert.That(dashyYaml, Does.Contain("https://jellyfin.new"));
            Assert.That(dashyYaml, Does.Contain("HandWrittenDashyEntry"));
            Assert.That(homepageYaml, Does.Contain("https://jellyfin.new"));
            Assert.That(homepageYaml, Does.Contain("HandWrittenHomepageEntry"));
        });
    }

    [Test]
    public async Task ProviderIdStopsPosting_PastStaleProviderTimeout_ItsEntriesAreRemovedFromBothDashboards()
    {
        // pi-turntable's Docker source (pi-turntable-docker) is gone; only its YAML file source
        // still posts. Traefik's entry must expire, while owntone (still posted) and a hand-written
        // copy tagged with the dead ProviderId but no _autogenerated must survive.
        using var dashyDir = TestTempDir.Create("dsm_cp_stale_dashy");
        using var homepageDir = TestTempDir.Create("dsm_cp_stale_hp");
        var dashyPath = dashyDir.RootedPath(DashyDashboardManager.ConfigFileName);
        var homepagePath = homepageDir.RootedPath(HomepageDashboardManager.ServicesFileName);

        File.WriteAllText(dashyPath, """
            ---
            sections:
            - name: Infrastructure
              items:
              - title: Traefik (pi-turntable)
                url: https://traefik.pi-turntable.example
                icon: favicon-local
                tags:
                - _autogenerated
                - host=pi-turntable
                - provider=pi-turntable-docker
              - title: Hand Copy
                url: https://hand.example
                icon: favicon-local
                tags:
                - host=pi-turntable
                - provider=pi-turntable-docker
            - name: Media
              items:
              - title: owntone
                url: https://owntone.example
                icon: favicon-local
                tags:
                - _autogenerated
                - host=pi-turntable
                - provider=pi-turntable-yamlfile
            """);

        File.WriteAllText(homepagePath, """
            - Infrastructure:
                - Traefik (pi-turntable):
                    href: https://traefik.pi-turntable.example
                    server: pi-turntable
                    _autogenerated: true
                    _providerId: pi-turntable-docker
                - Hand Copy:
                    href: https://hand.example
                    server: pi-turntable
                    _providerId: pi-turntable-docker
            - Media:
                - owntone:
                    href: https://owntone.example
                    server: pi-turntable
                    _autogenerated: true
                    _providerId: pi-turntable-yamlfile
            """);

        var time = new ManualTimeProvider();
        var processor = BuildProcessor(time, TimeSpan.FromMinutes(10),
            (DashboardManagerType.Dashy, dashyDir.Path),
            (DashboardManagerType.Homepage, homepageDir.Path));

        var owntone = new List<Service>
        {
            new Service("owntone", "https://owntone.example", "Media", null, null, "pi-turntable", false,
                providerId: "pi-turntable-yamlfile"),
        };

        // Posts arrive every 6 minutes, so no gap between POSTs exceeds the timeout.
        await processor.UpdateWithServicesFromProvider(owntone);
        time.Advance(TimeSpan.FromMinutes(6));
        var beforeTimeout = await processor.UpdateWithServicesFromProvider(owntone);
        time.Advance(TimeSpan.FromMinutes(6));
        var afterTimeout = await processor.UpdateWithServicesFromProvider(owntone);

        Assert.Multiple(() =>
        {
            foreach (var dashboard in new[] { "Dashy", "Homepage" })
            {
                Assert.That(beforeTimeout[dashboard].Select(s => s.Name), Does.Contain("Traefik (pi-turntable)"),
                    $"{dashboard}: 6 minutes unseen is within the 10-minute timeout");
                Assert.That(afterTimeout[dashboard].Select(s => s.Name),
                    Is.EquivalentTo(new[] { "Hand Copy", "owntone" }),
                    $"{dashboard}: 12 minutes unseen expires pi-turntable-docker's autogenerated entry only");
            }
        });

        var dashyYaml = await File.ReadAllTextAsync(dashyPath);
        var homepageYaml = await File.ReadAllTextAsync(homepagePath);
        Assert.Multiple(() =>
        {
            Assert.That(dashyYaml, Does.Not.Contain("https://traefik.pi-turntable.example"));
            Assert.That(homepageYaml, Does.Not.Contain("https://traefik.pi-turntable.example"));
            Assert.That(dashyYaml, Does.Contain("https://hand.example"));
            Assert.That(homepageYaml, Does.Contain("https://hand.example"));
        });
    }

