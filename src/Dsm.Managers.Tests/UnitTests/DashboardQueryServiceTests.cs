using Dsm.Managers.Configuration;
using Dsm.Managers.DashboardManagers;
using Dsm.Managers.HostBuilder;
using Dsm.Shared.Models;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace Dsm.Managers.Tests.UnitTests;

[CancelAfter(TestTimeouts.HungThresholdMs)]
public class DashboardQueryServiceTests : PerTestHostedTestBase
{
    [Test]
    public async Task ListServices_ReturnsTheMergedProviderState_WithoutHandWrittenEntries()
    {
        using var dashyDir = TestTempDir.Create("dsm_qs_merged");
        File.WriteAllText(dashyDir.RootedPath(DashyDashboardManager.ConfigFileName), """
            ---
            sections:
            - name: Media
              items:
              - title: Hand
                url: https://hand.example
                icon: favicon-local
                tags:
                - host=nas-01
            """);
        var host = BuildHost(dashyDir.Path);
        var processor = host.Services.GetRequiredService<DashboardCommandProcessor>();

        await processor.UpdateWithServicesFromProvider(new List<Service>
        {
            new Service("Forgejo", null, "development", null, null, "nas-01", false, providerId: "nas-01-docker"),
            new Service("Frigate", null, null, null, null, "nas-01", ignore: true, providerId: "nas-01-docker"),
        });
        await processor.UpdateWithServicesFromProvider(new List<Service>
        {
            new Service("Forgejo", "https://forgejo.example", null, null, null, "nas-01", false, providerId: "docker-01-traefik-2"),
            new Service("Frigate", "https://frigate.example", null, null, null, "nas-01", false, providerId: "docker-01-traefik-2"),
        });

        var services = await host.Services.GetRequiredService<DashboardQueryService>().ListServices();

        var forgejo = services.Single();
        Assert.Multiple(() =>
        {
            Assert.That(forgejo.Name, Is.EqualTo("Forgejo"));
            Assert.That(forgejo.Url, Is.EqualTo("https://forgejo.example"));
            Assert.That(forgejo.Category, Is.EqualTo("development"));
        });
    }

    [Test]
    public async Task ListServices_BeforeAnyPost_ReturnsTheSeededDashboardEntries()
    {
        using var dashyDir = TestTempDir.Create("dsm_qs_seed");
        File.WriteAllText(dashyDir.RootedPath(DashyDashboardManager.ConfigFileName), """
            ---
            sections:
            - name: Monitoring
              items:
              - title: Scrutiny
                url: https://scrutiny.example
                icon: hl-scrutiny
                tags:
                - _autogenerated
                - host=nas-01
                - provider=nas-01-docker
              - title: Hand
                url: https://hand.example
                icon: favicon-local
                tags:
                - host=nas-01
            """);
        var host = BuildHost(dashyDir.Path);

        var services = await host.Services.GetRequiredService<DashboardQueryService>().ListServices();

        Assert.That(services.Select(s => (s.Name, s.Url)),
            Is.EqualTo(new[] { ("Scrutiny", (string?)"https://scrutiny.example") }));
    }

    private IHost BuildHost(string dashyDirectory)
    {
        var managerConfigs = new List<DashboardManagerConfig>
        {
            new() { DashboardManagerType = DashboardManagerType.Dashy, DashboardConfigDirectoryPath = dashyDirectory },
        };
        return CreateHost(configureServices: services =>
        {
            services.AddDsmManagerServices();
            services.ConfigureOfflineIconHttpClients();
            services.AddTransient<IOptions<ManagerOptions>>(_ =>
                Options.Create(new ManagerOptions { DashboardManagers = managerConfigs }));
            services.AddTransient<IOptions<ServiceDefaultOptions>>(_ =>
                Options.Create(new ServiceDefaultOptions()));
            services.AddSingleton(sp => new ProviderServiceStore(
                Path.Combine(dashyDirectory, "dsm-state.json"),
                sp.GetRequiredService<IOptions<ManagerOptions>>(),
                sp.GetRequiredService<DashboardManagerFactory>(),
                sp.GetRequiredService<ILogger<ProviderServiceStore>>()));
        });
    }
}
