using Dsm.Managers.Configuration;
using Dsm.Managers.Services;
using Dsm.Shared.Models;
using Microsoft.Extensions.Options;

namespace Dsm.Managers.Tests.UnitTests;

[CancelAfter(TestTimeouts.HungThresholdMs)]
public class ServiceMergerTests
{
    private static readonly string[] NoIgnoredNames = [];

    [Test]
    public void SameNameAndHostname_FromTwoSources_MergeIntoOneOwnedByTheUrlSource()
    {
        var merged = Merge(
            Copy("Scrutiny", "https://scrutiny.example", "nas-01", "nas-01-docker"),
            Copy("Scrutiny", "https://scrutiny.example", "nas-01", "docker-01-traefik-2"));

        Assert.That(merged, Has.Count.EqualTo(1));
        Assert.That(merged[0].ProviderId, Is.EqualTo("docker-01-traefik-2"));
    }

    [Test]
    public void UrlLessDockerCopy_WithLabels_TraefikCopy_MergedEntryHasTraefikUrlAndLabelValues()
    {
        var merged = Merge(
            Copy("Forgejo", null, "nas-01", "nas-01-docker", category: "development", icon: "hl-forgejo",
                imageUrl: "https://img.example/forgejo.png", serviceDefaultsName: "forgejo"),
            Copy("Forgejo", "https://forgejo.example", "nas-01", "docker-01-traefik-2"));

        var forgejo = merged.Single();
        Assert.Multiple(() =>
        {
            Assert.That(forgejo.Url, Is.EqualTo("https://forgejo.example"));
            Assert.That(forgejo.Category, Is.EqualTo("development"));
            Assert.That(forgejo.Icon, Is.EqualTo("hl-forgejo"));
            Assert.That(forgejo.ImageUrl, Is.EqualTo("https://img.example/forgejo.png"));
            Assert.That(forgejo.ServiceDefaultsName, Is.EqualTo("forgejo"));
            Assert.That(forgejo.Autogenerated, Is.True);
        });
    }

    [Test]
    public void OneCopyIgnored_ServiceDropped()
    {
        var merged = Merge(
            Copy("Forgejo", null, "nas-01", "nas-01-docker", ignore: true),
            Copy("Forgejo", "https://forgejo.example", "nas-01", "docker-01-traefik-2"));

        Assert.That(merged, Is.Empty);
    }

    [Test]
    public void OneCopyNamedInIgnoredServiceNames_ServiceDropped()
    {
        var merged = new ServiceMerger(Defaults()).Merge(
            [
                Copy("Dashy", "https://dashy.example", "docker-01", "docker-01-traefik-0"),
                Copy("Dashy Web", "https://dashy.example", "docker-01", "docker-01-docker"),
            ],
            ["dashy"]);

        Assert.That(merged, Is.Empty);
    }

    [Test]
    public void NoCopyHasUrl_ServiceDropped()
    {
        var merged = Merge(Copy("Forgejo", null, "nas-01", "nas-01-docker", category: "development"));

        Assert.That(merged, Is.Empty);
    }

    [TestCase("docker-01-traefik-2", "media-01-docker", "https://plex.traefik")]
    [TestCase("docker-01-traefik-0", "media-01-docker", "https://plex.traefik")]
    [TestCase("media-01-docker", "media-01-swarm", "https://plex.docker")]
    [TestCase("media-01-swarm", "media-01-yamlfile", "https://plex.swarm")]
    [TestCase("media-01-yamlfile", "custom-source", "https://plex.yamlfile")]
    [TestCase("docker-01-traefik-2", "nas-01-traefik", "https://plex.traefik")]
    public void ConflictingUrls_UrlComesFromFirstTypeInTraefikDockerSwarmYamlOrder(
        string winningProviderId, string losingProviderId, string expectedUrl)
    {
        var merged = Merge(
            Copy("Plex", "https://plex.other", "media-01", losingProviderId),
            Copy("Plex", expectedUrl, "media-01", winningProviderId));

        Assert.That(merged.Single().Url, Is.EqualTo(expectedUrl));
        Assert.That(merged.Single().ProviderId, Is.EqualTo(winningProviderId));
    }

    [TestCase("nas-01-docker", "docker-01-traefik-2")]
    [TestCase("nas-01-swarm", "docker-01-traefik-2")]
    [TestCase("docker-01-traefik-2", "docker-01-yamlfile")]
    [TestCase("nas-01-docker", "nas-01-swarm")]
    [TestCase("docker-01-docker", "nas-01-docker")]
    public void ConflictingCategories_CategoryComesFromFirstTypeInDockerSwarmTraefikYamlOrder(
        string winningProviderId, string losingProviderId)
    {
        var merged = Merge(
            Copy("Immich", "https://immich.example", "nas-01", losingProviderId, category: "loser"),
            Copy("Immich", "https://immich.example", "nas-01", winningProviderId, category: "winner"));

        Assert.That(merged.Single().Category, Is.EqualTo("winner"));
    }

    [Test]
    public void SameUrlDifferentNames_NameComesFromTheDockerCopy()
    {
        var merged = Merge(
            Copy("Immich", "https://immich.example", "nas-01", "docker-01-traefik-2"),
            Copy("Photos", "https://immich.example", "nas-01", "nas-01-docker"));

        Assert.That(merged.Single().Name, Is.EqualTo("Photos"));
    }

    [Test]
    public void TraefikApiServiceAndUrlLessTraefikContainer_GroupedByTheirDefaultedName()
    {
        // The Traefik provider names its API router "traefik"; the Docker provider names the
        // container "Traefik". Only after defaults do both read "Traefik (nas-01)".
        var defaults = new ServiceDefaultOptions();
        defaults.Services["traefik"] = new ServiceConfig { NameWithHostnameFormatString = "Traefik (%s)" };

        var merged = new ServiceMerger(Defaults(defaults)).Merge(
            [
                Copy("traefik", "https://traefik.nas-01.example", "nas-01", "docker-01-traefik-2"),
                Copy("Traefik", null, "nas-01", "nas-01-docker", icon: "hl-traefik"),
            ],
            NoIgnoredNames);

        var traefik = merged.Single();
        Assert.That(traefik.Name, Is.EqualTo("Traefik (nas-01)"));
        Assert.That(traefik.Icon, Is.EqualTo("hl-traefik"));
    }

    [Test]
    public void DefaultsFillOnlyTheGapsLeftAfterMerging()
    {
        var defaults = new ServiceDefaultOptions();
        defaults.Services["plex"] = new ServiceConfig { Category = "media", Icon = "hl-plex" };

        var merged = new ServiceMerger(Defaults(defaults)).Merge(
            [
                Copy("Plex", "https://plex.example", "media-01", "docker-01-traefik-1"),
                Copy("Plex", null, "media-01", "media-01-docker", icon: "sh-plex"),
            ],
            NoIgnoredNames);

        Assert.That(merged.Single().Category, Is.EqualTo("media"), "no copy set one, so the default applies");
        Assert.That(merged.Single().Icon, Is.EqualTo("sh-plex"), "the label beats the default");
    }

    [Test]
    public void SameNameDifferentHostnames_StaySeparate()
    {
        var merged = Merge(
            Copy("Plex", "https://app.plex.tv/", "nas-01", "docker-01-yamlfile"),
            Copy("Plex", "https://app.plex.tv", "media-01", "media-01-docker"));

        Assert.That(merged.Select(s => s.Hostname), Is.EquivalentTo(new[] { "nas-01", "media-01" }));
    }

    [Test]
    public void ShuffledInput_ProducesTheSameOutput()
    {
        Service[] copies =
        [
            Copy("Scrutiny", "https://scrutiny.example", "nas-01", "nas-01-docker", category: "monitoring"),
            Copy("Scrutiny", "https://scrutiny.example", "nas-01", "docker-01-traefik-2"),
            Copy("Plex", "https://app.plex.tv", "media-01", "media-01-docker"),
            Copy("Plex", "https://app.plex.tv/", "nas-01", "docker-01-yamlfile"),
            Copy("Forgejo", null, "nas-01", "nas-01-docker", icon: "hl-forgejo"),
            Copy("Forgejo", "https://forgejo.example", "nas-01", "docker-01-traefik-2"),
        ];

        var forward = Merge(copies);
        var reversed = Merge(Enumerable.Reverse(copies).ToArray());

        Assert.That(reversed, Is.EqualTo(forward));
    }

    private static List<Service> Merge(params Service[] copies) =>
        new ServiceMerger(Defaults()).Merge(copies, NoIgnoredNames);

    private static ServiceWithDefaultsFactory Defaults(ServiceDefaultOptions? options = null) =>
        new(Options.Create(options ?? new ServiceDefaultOptions()));

    private static Service Copy(
        string name, string? url, string hostname, string providerId,
        string? category = null, string? icon = null, string? imageUrl = null,
        string? serviceDefaultsName = null, bool ignore = false) =>
        new(name, url, category, icon, imageUrl, hostname, ignore,
            serviceDefaultsName: serviceDefaultsName, providerId: providerId);
}
