using Dsm.Managers.Configuration;
using Dsm.Managers.DashboardManagers;
using Dsm.Managers.HostBuilder;
using Dsm.Shared.Models;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace Dsm.Managers.Tests.UnitTests;

[CancelAfter(TestTimeouts.HungThresholdMs)]
public class ProviderServiceStoreTests : PerTestHostedTestBase
{
    private const string DashyWithOneOwnedAndOneHandWrittenEntry = """
        ---
        sections:
        - name: Monitoring
          items:
          - title: Scrutiny
            url: https://scrutiny.example
            icon: hl-scrutiny
            tags:
            - _autogenerated
            - host=nas-01
            - provider=nas-01-docker
          - title: Hand
            url: https://hand.example
            icon: favicon-local
            tags:
            - host=nas-01
        """;

    [Test]
    public async Task SaveThenLoadInANewStore_RestoresEveryCopy()
    {
        using var dir = TestTempDir.Create("dsm_store_roundtrip");
        var statePath = dir.RootedPath("state.json");
        var first = BuildStore(dir.Path, statePath);
        await first.EnsureLoaded();
        first.Replace(
        [
            new Service("Forgejo", null, "development", "hl-forgejo", null, "nas-01", ignore: true, providerId: "nas-01-docker"),
            new Service("Scrutiny", "https://scrutiny.example", null, null, null, "nas-01", false,
                autogenerated: true, providerId: "docker-01-traefik-2"),
        ]);
        await first.Save();

        var second = BuildStore(dir.Path, statePath);
        await second.EnsureLoaded();

        Assert.That(second.Copies, Is.EquivalentTo(first.Copies));
    }

    [Test]
    public async Task Save_UnchangedCopies_DoesNotRewriteTheFile()
    {
        using var dir = TestTempDir.Create("dsm_store_unchanged");
        var statePath = dir.RootedPath("state.json");
        var store = BuildStore(dir.Path, statePath);
        await store.EnsureLoaded();
        Service[] copies =
        [
            new Service("Scrutiny", "https://scrutiny.example", null, null, null, "nas-01", false, providerId: "nas-01-docker"),
        ];
        store.Replace(copies);
        await store.Save();
        var backdated = new DateTime(2000, 1, 1, 0, 0, 0, DateTimeKind.Utc);
        File.SetLastWriteTimeUtc(statePath, backdated);

        store.Replace(copies);
        await store.Save();

        Assert.That(File.GetLastWriteTimeUtc(statePath), Is.EqualTo(backdated));
    }

    [Test]
    public async Task NoStateFile_SeedsFromTheFirstDashboardsOwnEntries()
    {
        using var dir = TestTempDir.Create("dsm_store_seed");
        File.WriteAllText(dir.RootedPath(DashyDashboardManager.ConfigFileName), DashyWithOneOwnedAndOneHandWrittenEntry);
        var store = BuildStore(dir.Path, dir.RootedPath("state.json"));

        await store.EnsureLoaded();

        Assert.That(store.Copies.Select(c => (c.Name, c.ProviderId)),
            Is.EqualTo(new[] { ("Scrutiny", (string?)"nas-01-docker") }));
    }

    [Test]
    public async Task CorruptStateFile_SeedsFromTheFirstDashboard()
    {
        using var dir = TestTempDir.Create("dsm_store_corrupt");
        File.WriteAllText(dir.RootedPath(DashyDashboardManager.ConfigFileName), DashyWithOneOwnedAndOneHandWrittenEntry);
        var statePath = dir.RootedPath("state.json");
        File.WriteAllText(statePath, "{ not json");
        var store = BuildStore(dir.Path, statePath);

        await store.EnsureLoaded();

        Assert.That(store.Copies.Select(c => c.Name), Is.EqualTo(new[] { "Scrutiny" }));
    }

    [Test]
    public async Task MissingStateDirectory_KeepsStateInMemory()
    {
        using var dir = TestTempDir.Create("dsm_store_memory");
        var missingDirectory = Path.Combine(dir.Path, "missing");
        var store = BuildStore(dir.Path, Path.Combine(missingDirectory, "state.json"));
        await store.EnsureLoaded();

        store.Replace(
        [
            new Service("Scrutiny", "https://scrutiny.example", null, null, null, "nas-01", false, providerId: "nas-01-docker"),
        ]);
        await store.Save();

        Assert.That(Directory.Exists(missingDirectory), Is.False);
        Assert.That(store.Copies.Select(c => c.Name), Is.EqualTo(new[] { "Scrutiny" }));
    }

    private ProviderServiceStore BuildStore(string dashyDirectory, string statePath)
    {
        var host = CreateHost(configureServices: services =>
        {
            services.AddDsmManagerServices();
            services.ConfigureOfflineIconHttpClients();
            services.AddTransient<IOptions<ManagerOptions>>(_ => Options.Create(new ManagerOptions
            {
                DashboardManagers =
                [
                    new DashboardManagerConfig
                    {
                        DashboardManagerType = DashboardManagerType.Dashy,
                        DashboardConfigDirectoryPath = dashyDirectory,
                    },
                ],
            }));
            services.AddTransient<IOptions<ServiceDefaultOptions>>(_ => Options.Create(new ServiceDefaultOptions()));
        });
        return new ProviderServiceStore(
            statePath,
            host.Services.GetRequiredService<IOptions<ManagerOptions>>(),
            host.Services.GetRequiredService<DashboardManagerFactory>(),
            host.Services.GetRequiredService<ILogger<ProviderServiceStore>>());
    }
}
